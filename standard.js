const languageSelect = document.getElementById('detailLanguage');
const topic = new URLSearchParams(window.location.search).get('topic');

function getLanguage() {
  const savedLanguage = localStorage.getItem('sti-language');
  if (['pl', 'de', 'en'].includes(savedLanguage)) return savedLanguage;
  const browserLanguage = (navigator.language || 'en').toLowerCase().split('-')[0];
  return ['pl', 'de', 'en'].includes(browserLanguage) ? browserLanguage : 'en';
}

function renderStandard(language) {
  const content = standardContent[topic] && standardContent[topic][language];
  const ui = interfaceText[language];
  document.documentElement.lang = language;
  languageSelect.value = language;
  document.getElementById('detailLanguageLabel').textContent = ui.language;
  document.getElementById('detailBack').textContent = ui.back;
  document.getElementById('detailContact').textContent = ui.contact;
  document.getElementById('detailCareers').textContent = ui.careers;
  document.getElementById('detailEyebrow').textContent = ui.eyebrow;
  document.getElementById('standardShortcutNav').setAttribute('aria-label', ui.eyebrow);
  document.querySelectorAll('[data-standard-label]').forEach(label => {
    label.textContent = ui[label.dataset.standardLabel];
  });
  document.querySelectorAll('[data-standard-image]').forEach(image => {
    image.src = 'assets/' + image.dataset.standardImage + language.toUpperCase() + '.jpeg';
  });

  const sectionsElement = document.getElementById('detailSections');
  sectionsElement.replaceChildren();
  if (!content) {
    document.getElementById('detailTitle').textContent = ui.missing;
    document.getElementById('detailTagline').textContent = '';
    document.getElementById('detailIntroLead').textContent = '';
    document.getElementById('detailIntroRest').textContent = '';
    document.getElementById('detailClosing').textContent = '';
    document.title = ui.missing + ' — EVELORA';
    return;
  }

  document.getElementById('detailTitle').textContent = content.title;
  document.getElementById('detailTagline').textContent = content.tagline;
  document.getElementById('detailIntroLead').textContent = content.introLead;
  document.getElementById('detailIntroRest').textContent = content.introRest;
  document.getElementById('detailClosing').textContent = content.closing;
  document.title = content.title + ' — EVELORA';

  for (const section of content.sections) {
    const sectionElement = document.createElement('section');
    sectionElement.className = 'standard-detail-topic';
    const heading = document.createElement('h2');
    heading.textContent = section.title;
    const list = document.createElement('ul');
    for (const [text, bold] of section.items) {
      const item = document.createElement('li');
      if (bold) {
        const emphasis = document.createElement('strong');
        emphasis.textContent = text;
        item.appendChild(emphasis);
      } else {
        item.textContent = text;
      }
      list.appendChild(item);
    }
    sectionElement.append(heading, list);
    sectionsElement.appendChild(sectionElement);
  }
}

const savedTextSize = localStorage.getItem('sti-text-size');
document.documentElement.classList.add('text-size-' + (['small', 'medium', 'large'].includes(savedTextSize) ? savedTextSize : 'medium'));

renderStandard(getLanguage());
languageSelect.addEventListener('change', event => {
  const language = event.target.value;
  localStorage.setItem('sti-language', language);
  renderStandard(language);
});
